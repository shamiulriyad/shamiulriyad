def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class Svg:
    def __init__(self, w, h):
        self.w, self.h, self.o = w, h, []

    def add(self, s):
        self.o.append(s)

    def text(self, x, y, t, size=20, weight=400, fill=INK, anchor="start", italic=False):
        st = ' font-style="italic"' if italic else ""
        self.add(f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" fill="{fill}" '
                 f'text-anchor="{anchor}"{st}>{esc(t)}</text>')

    def lines(self, x, y, rows, size=19, gap=None, **kw):
        gap = gap or size * 1.3
        for i, r in enumerate(rows):
            self.text(x, y + i * gap, r, size=size, **kw)

    def box(self, x, y, w, h, fill="#ffffff", stroke="#9fb0c6", sw=1.6, rx=8, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"{d}/>')

    def arrow(self, x1, y1, x2, y2, colour=MUTED, w=2, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{colour}" stroke-width="{w}"{d} marker-end="url(#ah)"/>')

    def path(self, d, colour=MUTED, w=2, dash=None, marker=True):
        ds = f' stroke-dasharray="{dash}"' if dash else ""
        m = ' marker-end="url(#ah)"' if marker else ""
        self.add(f'<path d="{d}" fill="none" stroke="{colour}" stroke-width="{w}"{ds}{m}/>')

    def render(self):
        defs = (f'<defs><marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto">'
                f'<path d="M0,0 L10,5 L0,10 z" fill="{MUTED}"/></marker>'
                f'<pattern id="hatch" width="8" height="8" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
                f'<rect width="8" height="8" fill="{UNC_BG}"/><rect width="3" height="8" fill="{UNCERTAIN}"/></pattern></defs>')
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" font-family="{FONT}">'
                + defs + f'<rect width="{self.w}" height="{self.h}" fill="#ffffff"/>' + "\n".join(self.o) + "</svg>")


